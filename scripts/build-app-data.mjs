// Bundles data/items.json, data/models.json and data/schedules/*.json into app/data.js
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = new URL("../data/", import.meta.url).pathname;
const items = JSON.parse(readFileSync(join(root, "items.json"), "utf8"));
const models = JSON.parse(readFileSync(join(root, "models.json"), "utf8"));
const registryMap = JSON.parse(readFileSync(join(root, "registry_map.json"), "utf8")).rules;
const dir = join(root, "schedules");
const schedules = readdirSync(dir).filter(f => f.endsWith(".json"))
  .map(f => JSON.parse(readFileSync(join(dir, f), "utf8")))
  .map(strip);
// Transcriber notes (provenance, what was or wasn't readable) stay in data/ for the data session and HANDOFF.
// They are not user-facing, so they never enter the bundle. Item-level `note` fields are user-facing and stay.
function strip(s) {
  const { notes, ...rest } = s;
  rest.sources = (s.sources || []).map(({ note, ...src }) => src);
  if (rest.specs) { const { _note, ...specs } = rest.specs; rest.specs = specs; }
  return rest;
}
const out = `// Generated by scripts/build-app-data.mjs. Do not edit by hand.\nwindow.TIPULIT_DATA = ${JSON.stringify({ items, models, schedules, registryMap })};\n`;
writeFileSync(new URL("../app/data.js", import.meta.url).pathname, out);
console.log(`bundled ${schedules.length} schedules, ${Object.keys(items).length} items`);
