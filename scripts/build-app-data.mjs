// Bundles data/items.json, data/models.json and data/schedules/*.json into app/data.js
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = new URL("../data/", import.meta.url).pathname;
const items = JSON.parse(readFileSync(join(root, "items.json"), "utf8"));
const models = JSON.parse(readFileSync(join(root, "models.json"), "utf8"));
const govMatch = JSON.parse(readFileSync(join(root, "gov-match.json"), "utf8")).rules;
const dir = join(root, "schedules");
const schedules = readdirSync(dir).filter(f => f.endsWith(".json"))
  .map(f => JSON.parse(readFileSync(join(dir, f), "utf8")));
const out = `// Generated by scripts/build-app-data.mjs. Do not edit by hand.\nwindow.TIPULIT_DATA = ${JSON.stringify({ items, models, schedules, govMatch })};\n`;
writeFileSync(new URL("../app/data.js", import.meta.url).pathname, out);
console.log(`bundled ${schedules.length} schedules, ${Object.keys(items).length} items`);
