// Removing a car: two taps on the car screen, the other car stays active; removing the last one opens add-car.
import { chromium } from "playwright";
const SITE = process.env.SITE_DIR || new URL("../../site", import.meta.url).pathname;
import { createServer } from "node:http"; import { readFileSync, existsSync } from "node:fs";
const srv = createServer((q, r) => { let f = SITE + q.url.split("?")[0]; if (f.endsWith("/")) f += "index.html"; if (!existsSync(f)) { r.statusCode = 404; return r.end(); } r.setHeader("content-type", f.endsWith(".js") ? "text/javascript" : f.endsWith(".css") ? "text/css" : f.endsWith(".json") ? "application/json" : "text/html; charset=utf-8"); r.end(readFileSync(f)); }).listen(8141);
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 400, height: 900 } });
const errs = []; p.on("pageerror", e => errs.push(e.message));
const ok = (c, m) => console.log((c ? "OK   " : "FAIL ") + m);
await p.goto("http://localhost:8141/"); await p.waitForTimeout(200);
const car = (plate, km) => ({ plate, schedule: "hyundai-i10-2014-2019", year: 2017, km, kmMonth: 1500, lastService: "2025-01", history: [] });
await p.evaluate(cs => localStorage.setItem("tipulit", JSON.stringify({ onboarded: true, user: { name: "מקס", via: "guest" }, cars: cs, active: 1 })), [car("11-111-11", 50000), car("22-222-22", 80000)]);
await p.reload(); await p.waitForTimeout(400);
const stored = () => p.evaluate(() => { const s = JSON.parse(localStorage.getItem("tipulit")); return { plates: s.cars.map(c => c.plate), active: s.active }; });
// profile list: each car has its own remove, and the list stays open
await p.click('#nav button[data-go="me"]'); await p.waitForTimeout(300);
ok(await p.locator("#me-cars [data-del]").count() === 2, "profile list has a remove button per car");
await p.screenshot({ path: (process.env.SHOTS || "/tmp") + "/remove-car-me.png" });
await p.click('#me-cars [data-del="0"]'); await p.waitForTimeout(100);
ok((await stored()).plates.length === 2, "profile: first tap only asks");
await p.click('#me-cars [data-del="0"]'); await p.waitForTimeout(400);
let m = await stored();
ok(m.plates.join() === "22-222-22" && m.active === 0 && !(await p.locator("#s-me").isHidden()) && await p.locator("#me-cars [data-del]").count() === 1, "profile: removes that car, keeps the active one, stays on the profile: " + JSON.stringify(m));
await p.evaluate(cs => { const s = JSON.parse(localStorage.getItem("tipulit")); s.cars.unshift(cs); s.active = 1; localStorage.setItem("tipulit", JSON.stringify(s)); }, car("11-111-11", 50000));
await p.reload(); await p.waitForTimeout(400);
await p.click('#nav button[data-go="car"]'); await p.waitForTimeout(300);
ok(await p.locator("#car-remove").isVisible(), "car screen has a remove button");
await p.click("#car-remove"); await p.waitForTimeout(100);
ok((await stored()).plates.length === 2 && /בטוח/.test(await p.locator("#car-remove").innerText()), "first tap only asks");
await p.click("#car-remove"); await p.waitForTimeout(400);
let s = await stored();
ok(s.plates.join() === "11-111-11" && s.active === 0, "second tap removes the active car: " + JSON.stringify(s));
ok(!(await p.locator("#s-home").isHidden()), "back on home with the other car");
await p.click('#nav button[data-go="car"]'); await p.waitForTimeout(300);
ok(/הסר את הרכב/.test(await p.locator("#car-remove").innerText()), "button text resets for the next car");
await p.click("#car-remove"); await p.click("#car-remove"); await p.waitForTimeout(400);
s = await stored();
ok(s.plates.length === 0 && !(await p.locator("#s-add").isHidden()), "removing the last car opens add-car");
console.log("errors:", errs);
await b.close(); srv.close();
